"""Build the shared, offline lexicon and browsable lists from vendored sources."""
import hashlib
import json
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
BASE = ROOT / 'data/content-filter'
SOURCES = {'politics': ['politics.txt', 'politics-extra.txt'], 'adult': ['adult.txt'], 'ads': ['ads.txt']}
exclusions = json.loads((BASE / 'exclusions.json').read_text())
words = {}
removed = {}
for cat, files in SOURCES.items():
    raw = sorted(set(w.strip() for f in files for w in (BASE/'source'/f).read_text(encoding='utf-8-sig').splitlines() if w.strip()))
    words[cat] = [w for w in raw if len(w) >= 2 and w not in exclusions.get(cat, [])]
    removed[cat] = [w for w in raw if w not in words[cat]]
words.update(json.loads((BASE/'custom.json').read_text()))
words = {k: sorted(set(v)) for k, v in words.items()}
for cat, values in words.items():
    (BASE/(cat+'.txt')).write_text('\n'.join(values)+'\n', encoding='utf-8')
all_words = sorted(set(w for values in words.values() for w in values))
(BASE/'all.txt').write_text('\n'.join(all_words)+'\n', encoding='utf-8')
(BASE/'excluded.json').write_text(json.dumps(removed, ensure_ascii=False, indent=2)+'\n', encoding='utf-8')
manifest = {'source': 'https://github.com/konsheng/Sensitive-lexicon', 'sourceCommit': '68a595fb24d31bd9f882c081b4252443a69ac57b', 'license': 'MIT', 'categories': {k:len(v) for k,v in words.items()}, 'uniqueWords':len(all_words), 'sha256':hashlib.sha256((BASE/'all.txt').read_bytes()).hexdigest()}
(BASE/'manifest.json').write_text(json.dumps(manifest,ensure_ascii=False,indent=2)+'\n')
data = {'categories':words, 'version':manifest['sha256'][:12]}
license_notice = '/*\n' + (BASE/'SOURCE-LICENSE').read_text().rstrip() + '\n*/\n'
(ROOT/'js/data/content-words.js').write_text(license_notice + '// Generated by tools/build_content_words.py. Source/license: data/content-filter/README.md\nvar CONTENT_WORDS = '+json.dumps(data,ensure_ascii=False,separators=(',',':'))+';\nif (typeof module !== "undefined") module.exports = CONTENT_WORDS;\n', encoding='utf-8')
print(json.dumps(manifest, ensure_ascii=False))
